/**
 * Resolves a governorate profile dynamically by ID, Arabic name, or English name,
 * and synthesizes a clean fallback profile if a new governorate is added to the JSON database.
 */
export function getGovernorateProfile(
  governorateIdOrGov: string | Governorate,
  governorateHint?: Governorate
): GovernorateProfile | undefined {
  const gov = typeof governorateIdOrGov === 'string' ? governorateHint : governorateIdOrGov;
  const id = typeof governorateIdOrGov === 'string' ? governorateIdOrGov : governorateIdOrGov.id;

  if (GOVERNORATE_PROFILES[id]) {
    return GOVERNORATE_PROFILES[id];
  }

  const slug = resolveCanonicalGovernorateSlug(id, gov?.name_en, gov?.name_ar);
  if (slug && GOVERNORATE_PROFILES[slug]) {
    return {
      ...GOVERNORATE_PROFILES[slug],
      governorate_id: id,
    };
  }

  if (gov) {
    return {
      governorate_id: gov.id,
      nicknames_ar: [gov.name_ar, gov.region],
      overview_ar: `تقع محافظة ${gov.name_ar} في إقليم ${gov.region} من العراق، وتحتضن مجموعة مميزة من المعالم التاريخية والدينية والطبيعية الموثّقة في قاعدة بيانات أرض السواد.`,
      cultural_identity_ar: `تعكس محافظة ${gov.name_ar} تنوّع التراث العراقي الأصيل وروح الضيافة والعراقة الممتدة عبر تاريخ بلاد الرافدين.`,
      traditions_cuisine_ar: `تزخر المحافظة بمأكولاتها التراثية العراقية وأسواقها الشعبية التي تعبّر عن هوية إقليم ${gov.region}.`,
      best_time_to_visit_ar: 'من أكتوبر إلى أبريل (الأشهر المعتدلة والمناسبة للزيارات الميدانية).',
    };
  }

  return undefined;
}

/**
 * Builds a profile lookup map keyed strictly by the active governorate IDs in landmarks.json.
 */
export function buildGovernorateProfilesMap(
  governorates: Governorate[]
): Record<string, GovernorateProfile> {
  const map: Record<string, GovernorateProfile> = {};
  for (const gov of governorates) {
    const resolved = getGovernorateProfile(gov);
    if (resolved) {
      map[gov.id] = { ...resolved, governorate_id: gov.id };
    }
  }
  return map;
}
