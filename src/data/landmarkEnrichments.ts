function normalizeForEnrichment(input: string): string {
  return input
    .trim()
    .toLowerCase()
    .replace(/[\u064B-\u065F\u0670\u0640]/g, '')
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/\s+/g, ' ');
}

function findEnrichmentForLandmark(landmark: Landmark): LandmarkRichContent | undefined {
  if (LANDMARK_ENRICHMENTS[landmark.id]) {
    return LANDMARK_ENRICHMENTS[landmark.id];
  }
  const haystack = normalizeForEnrichment(`${landmark.name_ar} ${landmark.name_en}`);
  for (const matcher of ENRICHMENT_NAME_MATCHERS) {
    if (matcher.patterns.some((p) => haystack.includes(p))) {
      return LANDMARK_ENRICHMENTS[matcher.key];
    }
  }
  return undefined;
}

export function isMissingOriginalField(value?: string | null): boolean {
  if (!value) return true;
  const trimmed = value.trim();
  return (
    trimmed.length === 0 ||
    trimmed.includes('غير محدد في البيانات الأصلية') ||
    trimmed.includes('غير محددة في البيانات الأصلية')
  );
}

export function getDisplayBestTimeToVisit(landmark: Landmark): string {
  if (!isMissingOriginalField(landmark.best_time_to_visit)) {
    return landmark.best_time_to_visit;
  }
  if (landmark.category === 'religious') {
    return 'مفتوح للزيارة على مدار العام، وتكون الأجواء ألطف مناخياً بين شهري أكتوبر وأبريل.';
  }
  if (landmark.category === 'nature_tourism') {
    return 'فصل الربيع (مارس – مايو) وأشهر الصيف المعتدلة في المناطق الجبلية، أو من نوفمبر إلى مارس للمناطق الجنوبية والأهوار.';
  }
  return 'من أكتوبر إلى أبريل (الأشهر المعتدلة والمثالية لاستكشاف المواقع الأثرية والتاريخية).';
}

export function getDisplayVisitorTips(landmark: Landmark): string {
  if (!isMissingOriginalField(landmark.visitor_tips)) {
    return landmark.visitor_tips;
  }
  if (landmark.category === 'religious') {
    return 'يُستحب الالتزام باللباس المحتشم ومراعاة قدسية المكان وهدوئه، مع التحقق من أوقات الزيارة والخدمات المحلية المتاحة.';
  }
  if (landmark.category === 'nature_tourism') {
    return 'يُنصح بارتداء أحذية مريحة واصطحاب الماء ووسائل الحماية من الشمس، مع المحافظة التامة على نظافة البيئة الطبيعية.';
  }
  return 'يُنصح بزيارة الموقع في ساعات الصباح أو قبيل الغروب، وارتداء أحذية مريحة للمشي، مع احترام الأسوار والمعالم الأثرية.';
}

export function getLandmarkRichContent(landmark: Landmark): LandmarkRichContent {
  const existing = findEnrichmentForLandmark(landmark);
  const isReligious = landmark.category === 'religious';
  const isArchaeological = landmark.category === 'archaeological';
  const govLabel =
    landmark.governorate_id === 'IQ-NATIONAL'
      ? 'العراق'
      : `محافظة ${landmark.governorate_ar}`;

  const fallbackHistorical =
    existing?.historical_architectural_ar ??
    `${landmark.description_ar} يندرج هذا المعلم ضمن نطاق «${landmark.era || landmark.category_ar}» في ${govLabel}، ويبرز كأحد الشواهد التراثية والمعمارية الأصيلة في المنطقة.`;

  const fallbackSignificance =
    existing?.significance_ar ??
    (isReligious
      ? `يحظى هذا الموقع الديني بمكانة روحية رفيعة في وجدان أهالي ${govLabel} وزوار العراق، ويشكّل مقصداً للسكينة والزيارة.`
      : isArchaeological
        ? `يمثّل هذا الموقع الأثري شاهداً موثّقاً على الحضارات المتعاقبة في بلاد الرافدين وعمق الإرث الإنساني في ${govLabel}.`
        : `يشكّل هذا المعلم الطبيعي والسياحي متنفساً بيئياً بارزاً يبرز تنوّع الطبيعة العراقية في ${govLabel}.`);

  const fallbackEtiquette =
    existing?.dress_code_etiquette_ar ??
    (isReligious
      ? 'يُرجى الالتزام باللباس المحتشم واحترام قدسية المكان وهدوئه.'
      : 'يُنصح بارتداء ملابس وأحذية مريحة مناسبة للزيارة والمشي، مع الحفاظ على نظافة الموقع.');

  const fallbackAccessibility =
    existing?.accessibility_ar ??
    'يُفضّل التخطيط المسبق للوصول بالسيارة والتحقق من ساعات الزيارة المحلية قبل التوجه للموقع.';

  return {
    historical_architectural_ar:
      landmark.historical_architectural_ar?.trim() || fallbackHistorical,
    significance_ar: landmark.significance_ar?.trim() || fallbackSignificance,
    dress_code_etiquette_ar:
      landmark.dress_code_etiquette_ar?.trim() || fallbackEtiquette,
    accessibility_ar: landmark.accessibility_ar?.trim() || fallbackAccessibility,
  };
}
